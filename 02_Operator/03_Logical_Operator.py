# type of logical operator 

# 1.AND 
# 2.OR 
# 3.NOT 

"and :- if both case are 'TRUE' it gives 'TRUE' other wise 'FALSE' "

"or:- if both case are 'FALSE' it gives 'FALSE' other wise 'TRUE' "

"not:- it gives us opposite value of any input "


# Examples 

a =  True

b =  False

c =  True

d =  False




print(a and b ) # Output = False

print(a and c ) # Output = True

print(a or b )  # Output = True

